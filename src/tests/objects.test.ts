import {cases, compilationError, runtimeError} from "./utils";
import {StaticErrorType} from "../ast";
import {RuntimeErrorType} from "../Interpreter";

describe('Matte Interpreter Objects', () => {
    describe('Records', () => {
        it('create function Point', () => {
            cases(`
            record Point(double x, double y) { }
            
            Point create() {  
                return new Point(1.2,-3.4);
            }
            `,
                ["create()", {$type: "Point", x: 1.2, y: -3.4}]);
        })

        it('Point int', () => {
            cases(`
            record Point(int x, int y) { }    
            `,
                ["new Point(1, -3)", {$type: "Point", x: 1, y: -3}]);
        })

        it('constructor', () => {
            cases(`
            record Point(double x, double y) { }    
            `,
                ["new Point(1.2, -3.4)", {$type: "Point", x: 1.2, y: -3.4}]);
        })

        it('field access', () => {
            cases(`
            record Point(double x, double y) { }    
            `,
                ["new Point(1.2, -3.4).x", 1.2],
                ["new Point(1.2, -3.4).y", -3.4]);
        })

        // inspector methods can be overridden by user defined methods, but should be generated by default for all fields
        it('inspector method', () => {
            cases(`
            record Point(double x, double y) { }    
            `,
                ["new Point(1.2, -3.4).x()", 1.2],
                ["new Point(1.2, -3.4).y()", -3.4]);
        })

        it('inspector method overridden', () => {
            cases(`
            record Point(double x, double y) { 
                double x() {
                    return x * 2;
                }
            }    
            `,
                ["new Point(1.2, -3.4).x()", 2.4]
            )
        })

        it('record method not found', () => {
            compilationError(`
            record Point(double x, double y) { 
                double test() {
                    return z();
                }
            }`, StaticErrorType.MethodNotFound,
                "new Point(1.2, -3.4).test()"
            )
        })

        it('field not found', () => {
            compilationError(`
            record Point(double x, double y) {
             double sum() {
                    return x + z;
             }
            }
            `, StaticErrorType.UndeclaredVariable);
        })

        it('record method direct fields', () => {
            cases(`
            record Point(double x, double y) { 
                double sum() {
                    return x + y;
                }
                  Point scale(double factor) {
                    return new Point(x * factor, y * factor);
                }
            }
            `,
                ["new Point(1.2, -3.4).sum()", -2.2],
                ["new Point(1.2, -3.4).scale(2.0)", {$type: "Point", x: 2.4, y: -6.8}]
            )
        })

        it('record method inspectors', () => {
            cases(`
            record Point(double x, double y) { 
                double sum() {
                    return x() + y();
                }
            }
            `,
                ["new Point(1.2, -3.4).sum()", -2.2]
            )
        })

        it('record method this fields', () => {
            cases(`
            record Point(double x, double y) { 
                Point sum(double x, double y) {
                    return new Point(this.x + x, this.y + y);
                }
            }
            `,
                ["new Point(1.2, -3.4).sum(1.0, 2.0)", {$type: "Point",x: 2.2, y: -1.4}])
        })

        it('final field', () => {
            compilationError(`
            record Point(double x, double y) { 
                void setX(double newX) {
                    x = newX;
                }
            }    
            `, StaticErrorType.ImmutableVariable);
        })

        it('call on reference', () => {
            cases(`
            record Point(double x, double y) { 
                double sum() {
                    return x + y;
                }
                double sumScale(double factor) {
                    Point p = new Point(x * factor, y * factor);
                    double s = p.sum();
                    return s;
                }
            }
            `,
                ["new Point(1.2, -3.4).sumScale(2.0)", -4.4]
            )
        })

        it('call on this', () => {
            cases(`
            record Point(double x, double y) { 
                double sum() {
                    return x + y;
                }
                
                 double sumThis() {
                    return this.sum();
                }
            }
            `,
                ["new Point(1.2, -3.4).sumThis()", -2.2]
            )
        })

        it('field on null', () => {
            runtimeError(`
            record Point(double x, double y) { 
              
            }
            
            void main() {
                Point r = null;
                double x = r.x;
            }
            `,
                RuntimeErrorType.NullPointer,
                "main()"
            )
        })
    })

    describe('Classes', () => {
        it('turtle', () => {
            cases(`
            class Turtle {
                int x = 0;
                int y = 0;
                int directionX = 1;
                int directionY = 0;
            
                void move() {
                    x = x + directionX;
                    y = y + directionY;
                }
            
                void rotateRight() {
                    if(directionX == 0) {
                        directionX = directionY == 1 ? -1 : 1;
                        directionY = 0;
                    }
                    else {
                        directionY = directionX == 1 ? 1 : -1;
                        directionX = 0;
                    }
                }
            }
            `,
                ["new Turtle()", {$type: "Turtle", x: 0, y: 0, directionX: 1, directionY: 0}]);
        })
    })
})
